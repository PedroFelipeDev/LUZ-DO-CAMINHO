USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- Reading Logs Policies (User specific)
CREATE POLICY "Users can manage their own reading logs" 
ON public.reading_logs FOR ALL 
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);
